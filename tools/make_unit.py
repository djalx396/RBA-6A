# Writes Source/UnitElRey.h from the fitted parameters (fit/params_*.json) and the EQ fit.
import json, sys
P=json.load(open(sys.argv[1])); EQ=json.load(open(sys.argv[2])); out=sys.argv[3]
T={"hp":"HP","lp":"LP","pk":"Peak","hs":"HighShelf","ls":"LowShelf","hp1":"HP1"}
def bands(spec,p):
    g=p[0]; i=1; L=[]
    for kind,n in spec:
        if kind=="hp1": L.append(f"{{ BQ::HP1, {p[i]:.6g}, 0.707, 0 }}"); i+=1
        elif kind in("hp","lp"): L.append(f"{{ BQ::{T[kind]}, {p[i]:.6g}, {p[i+1]:.6g}, 0 }}"); i+=2
        else: L.append(f"{{ BQ::{T[kind]}, {p[i]:.6g}, {p[i+1]:.6g}, {p[i+2]:.6g} }}"); i+=3
    return g, L
gb,lb=bands(EQ["bump_spec"],EQ["bump"]); gf,lf=bands(EQ["flat_spec"],EQ["flat"])
f=lambda k: f"{P[k]:.8g}"
src=f'''// UnitElRey.h — GENERATED by tools/make_unit.py from the El Rey 2 fit (96 kHz, HYP, OVS 32x captures).
// Do not edit by hand: re-run the fit and the generator.
#pragma once
#include "RbaCore.h"

namespace rba
{{
inline Unit makeElRey()
{{
    Unit u;
    u.bumpGainDb = {gb:.6g};
    u.bump = {{ {", ".join(lb)} }};
    u.flatGainDb = {gf:.6g};
    u.flat = {{ {", ".join(lf)} }};
    u.colour = {{ {f("col_fc")}, {f("col_gamma")}, {f("col_a2")}, {f("col_a3")}, {f("col_L")}, {f("col_p")}, {f("col_asym")} }};
    u.drive  = {{ {f("drv_fc")}, {f("drv_gamma")}, {f("drv_a2")}, {f("drv_a3")}, {f("drv_L")}, {f("drv_p")}, {f("drv_asym")} }};
    u.T0 = {f("T0")}; u.slope = {f("slope")}; u.knee = {f("knee")}; u.detPow = {f("detPow")};
    {"; ".join(f"u.attackKnots[{i}] = {v:.8g}" for i,v in enumerate(P["attackKnots"]))};
    {"; ".join(f"u.releaseKnots[{i}] = {v:.8g}" for i,v in enumerate(P["releaseKnots"]))};
    u.scQ = {f("scQ")}; u.scScale = {P.get("scScale",1.0):.8g};
    u.sqK = {P.get("sqK",0):.8g}; u.sqT = {P.get("sqT",0):.8g}; u.sqW = {P.get("sqW",6):.8g}; u.sqAtk = {P.get("sqAtk",0.002):.8g}; u.sqRel = {P.get("sqRel",0.05):.8g};
    u.k3max = {f("k3max")}; u.k3tau = {f("k3tau")}; u.k3base = {f("k3base")};
    u.thump = {f("thump") if P.get("thump",0)>0 else "0.02"};
    return u;
}}
}} // namespace rba
'''
open(out,"w").write(src); print("wrote",out)
